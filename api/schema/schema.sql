-- Bastion relational schema used by the SQLite driver.
-- Column names match the SQL already issued by routes and modules.

CREATE TABLE IF NOT EXISTS USER (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  NAME TEXT,
  PROFILEPICTURE TEXT,
  ABOUT TEXT,
  EMAIL TEXT,
  PASSWORD TEXT,
  TOKEN TEXT,
  ISCOACH INTEGER DEFAULT 0,
  COACHID INTEGER DEFAULT -1,
  ADMIN INTEGER,
  LOCATION TEXT,
  GENDER TEXT
);

CREATE TABLE IF NOT EXISTS SURVEY (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USERID INTEGER,
  PROMPT TEXT,
  QUESTIONTYPE TEXT,
  INPUTANSWER TEXT,
  MULTISELECTANSWER TEXT
);

CREATE TABLE IF NOT EXISTS PRICINGS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  TITLE TEXT,
  DESCRIPTION TEXT,
  PRICE REAL
);

CREATE TABLE IF NOT EXISTS PRICINGS_FEATURES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  PRICINGID INTEGER,
  FEATURE TEXT
);

CREATE TABLE IF NOT EXISTS PRICINGS_STRIPE (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  PRICINGID INTEGER,
  STRIPEPRODUCTID TEXT,
  STRIPEPRICEID TEXT
);

CREATE TABLE IF NOT EXISTS BANKING (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USERID INTEGER,
  STRIPEID TEXT
);

CREATE TABLE IF NOT EXISTS COACH_PRODUCT (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  PRODUCTID TEXT
);

CREATE TABLE IF NOT EXISTS PLAN (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CLIENTID INTEGER,
  COACHID INTEGER,
  PRICINGID INTEGER,
  STARTDATE TEXT,
  ENDDATE TEXT,
  ACTIVE INTEGER DEFAULT 0,
  STRIPESUBSCRIPTIONID TEXT
);

CREATE TABLE IF NOT EXISTS OFFERS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CLIENTID INTEGER,
  COACHID INTEGER,
  PRICINGID INTEGER
);

CREATE TABLE IF NOT EXISTS ASSIGNCOACHES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  CLIENTID INTEGER
);

CREATE TABLE IF NOT EXISTS MESSAGES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  FROMID INTEGER,
  TOID INTEGER,
  MESSAGE TEXT
);

CREATE TABLE IF NOT EXISTS REVIEWS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  CLIENTID INTEGER,
  REVIEW TEXT,
  BEFORERESOURCE TEXT,
  AFTERRESOURCE TEXT
);

CREATE TABLE IF NOT EXISTS CERTIFICATIONS (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  CERTIFICATION TEXT,
  RESOURCE TEXT,
  COMPLETIONDATE TEXT,
  APPROVED INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS COACHLANGUAGES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  LANGUAGE TEXT,
  FLUENCY TEXT
);

CREATE TABLE IF NOT EXISTS COACHATTRIBUTES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  ATTRIBUTE1 TEXT,
  ATTRIBUTE2 TEXT,
  ATTRIBUTE3 TEXT
);

CREATE TABLE IF NOT EXISTS COACHSPEC (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  SPEC1 TEXT,
  SPEC2 TEXT,
  SPEC3 TEXT
);

CREATE TABLE IF NOT EXISTS COACHACCOUNTABLE (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  ACCOUNTABLE TEXT
);

CREATE TABLE IF NOT EXISTS COACHCOMP (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  COMP TEXT
);

CREATE TABLE IF NOT EXISTS COACHCIRC (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  COACHID INTEGER,
  CIRC TEXT
);

CREATE TABLE IF NOT EXISTS RESETPASSWORD (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  USERID INTEGER,
  RESETTOKEN TEXT,
  EXPIRES INTEGER
);
